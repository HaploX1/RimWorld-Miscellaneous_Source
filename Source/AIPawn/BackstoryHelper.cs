using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
//using System.Threading.Tasks;

using UnityEngine;
using RimWorld;
using Verse;

namespace AIPawn
{
    /// <summary>
    /// Provides the work restriction backstories of the MAI.
    /// </summary>
    /// <remarks>
    /// RimWorld 1.6: the backstories are no longer created and registered at runtime.
    /// The 1.3 version built 16.384 Backstory objects during startup, pushed them into
    /// BackstoryDatabase and removed them again once the AI had taken one. That design cannot be
    /// reproduced on 1.6, for two reasons:
    ///   1. Backstory and BackstoryDatabase do not exist anymore. 1.6 only accepts BackstoryDefs
    ///      that were loaded from XML.
    ///   2. DefDatabase&lt;BackstoryDef&gt;.Remove is private, so a mod can neither unregister a def
    ///      nor avoid the global re-index a removal would trigger.
    /// Instead the backstories that are actually needed ship as XML defs in
    /// Defs/BackstoryDefs/AIPawn_Backstories_MAI.xml, generated by
    /// .hermes/tools/generate_mai_backstories.py. That script uses the same def name rule as
    /// GetBackstoryUniqueKey(), so XML and code cannot drift apart by hand.
    ///
    /// The defs are kept away from every other pawn by two independent guards:
    /// shuffleable = false excludes them from PawnBioAndNameGenerator, and
    /// requiresSpawnCategory = true together with the exclusive spawn category "MAIInternal"
    /// makes sure no pawn kind can ever match them.
    ///
    /// Only the work tags AIPawnGenerator.GetBackstory() can actually produce are shipped:
    /// Artistic (always) plus any subset of the nine research gated tags, which is 2^9 = 512 defs.
    /// </remarks>
    /// <author>Haplo</author>
    /// <permission>For usage of this code, please look at the license information.</permission>
    [StaticConstructorOnStartup]
    public class BackstoryHelper
    {
        public static string BackstoryDefNameIdentifier = "MAI";
        public static string BackstoryDefNameIdentifierDisabled = "_off_";

        /// <summary>
        /// The work tags the AI can never learn, no matter what has been researched.
        /// </summary>
        /// <returns></returns>
        public static WorkTags GetBasicWorkDisables()
        {
            return WorkTags.Artistic;
        }

        /// <summary>
        /// Builds the def name of the work restriction backstory for the given work tags.
        /// </summary>
        /// <remarks>
        /// The tag order is the order of the WorkTags enum itself (ascending flag value), which is
        /// what WorkTags.ToString() produces, and the tags are joined with "_". That is exactly the
        /// string the 1.3 version used as a BackstoryDatabase identifier, and it is also the rule the
        /// generator script uses for the def names, so this string is the contract between this class
        /// and AIPawn_Backstories_MAI.xml.
        /// </remarks>
        /// <param name="workDisables"></param>
        /// <returns></returns>
        public static string GetBackstoryUniqueKey(WorkTags workDisables)
        {
            string baseBackstoryDefName = BackstoryDefNameIdentifier + BackstoryDefNameIdentifierDisabled;
            string ukey = baseBackstoryDefName + workDisables.ToString().Replace(", ", "_");

            return ukey;
        }

        /// <summary>
        /// Looks up the work restriction backstory for the given work tags.
        /// </summary>
        /// <param name="workDisables"></param>
        /// <returns>The matching def, or null if it does not exist.</returns>
        public static BackstoryDef GetBackstoryDef(WorkTags workDisables)
        {
            return DefDatabase<BackstoryDef>.GetNamedSilentFail(GetBackstoryUniqueKey(workDisables));
        }

        /// <summary>
        /// True if the given backstory is one of the generated work restriction backstories.
        /// </summary>
        /// <param name="backstory"></param>
        /// <returns></returns>
        public static bool IsWorkRestrictionBackstory(BackstoryDef backstory)
        {
            if (backstory == null)
                return false;

            return backstory.defName.StartsWith(BackstoryDefNameIdentifier + BackstoryDefNameIdentifierDisabled);
        }
    }
}
